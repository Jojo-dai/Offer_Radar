-- ------------------------------------------------------------
-- 第 1 段：建表
-- ------------------------------------------------------------

-- 求职画像（可多版本，同一用户仅一条 is_active = true）
CREATE TABLE IF NOT EXISTS profiles (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id          text NOT NULL DEFAULT auth.uid(),
  owner_name        text,
  resume_filename   text,
  resume_text       text,
  competitiveness   jsonb,          -- ["10 年 B 端解决方案", ...]
  target_profile    jsonb,          -- {roles, level, industries, cities, cities_en}
  keywords          jsonb,          -- 中文关键词（猎聘用）
  keywords_en       jsonb,          -- 英文关键词（领聘用）
  chat_log          jsonb,          -- 多轮调整对话记录
  greeting_template text,           -- 打招呼用语模板
  is_active         boolean NOT NULL DEFAULT false,
  confirmed         boolean NOT NULL DEFAULT false,
  created_at        timestamptz NOT NULL DEFAULT now()
);

-- 岗位池（全生命周期）
CREATE TABLE IF NOT EXISTS jobs (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id      text NOT NULL DEFAULT auth.uid(),
  owner_name    text,
  company       text NOT NULL,
  position      text NOT NULL,
  jd_summary    text,
  salary        text,
  location      text,
  source_url    text,
  jd_text       text,
  match_score   integer,
  match_reason  text,
  status        text NOT NULL DEFAULT '待确认',
  platform      text DEFAULT '猎聘',
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- 岗位事件流
CREATE TABLE IF NOT EXISTS job_events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    text NOT NULL DEFAULT auth.uid(),
  owner_name  text,
  job_id      bigint NOT NULL,
  event_type  text NOT NULL,
  note        text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- 采集运行记录 / 手动请求队列
CREATE TABLE IF NOT EXISTS agent_tasks (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id      text DEFAULT auth.uid(),   -- 注意：text，不是 uuid
  owner_name    text,
  type          text NOT NULL DEFAULT 'collect_now',   -- collect_now | collect_scheduled
  status        text NOT NULL DEFAULT 'pending',       -- pending|processing|done|failed|merged
  note          text,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  processed_at  timestamptz
);

-- 常用索引
CREATE INDEX IF NOT EXISTS jobs_owner_status_idx   ON jobs (owner_id, status);
CREATE INDEX IF NOT EXISTS jobs_owner_score_idx    ON jobs (owner_id, match_score DESC);
CREATE INDEX IF NOT EXISTS events_job_idx          ON job_events (job_id);
CREATE INDEX IF NOT EXISTS tasks_owner_type_idx    ON agent_tasks (owner_id, type, status);


-- ------------------------------------------------------------
-- 第 2 段：授权（漏掉这段会得到"策略看起来失效"的 42501）
-- ------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON profiles    TO authenticated, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON jobs        TO authenticated, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON job_events  TO authenticated, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON agent_tasks TO authenticated, anon;

GRANT USAGE, SELECT ON SEQUENCE profiles_id_seq   TO authenticated, anon;
GRANT USAGE, SELECT ON SEQUENCE jobs_id_seq       TO authenticated, anon;
GRANT USAGE, SELECT ON SEQUENCE job_events_id_seq TO authenticated, anon;


-- ------------------------------------------------------------
-- 第 3 段：行级隔离（owner-only，逐表执行）
-- ------------------------------------------------------------
ALTER TABLE profiles    ENABLE ROW LEVEL SECURITY;
ALTER TABLE jobs        ENABLE ROW LEVEL SECURITY;
ALTER TABLE job_events  ENABLE ROW LEVEL SECURITY;
ALTER TABLE agent_tasks ENABLE ROW LEVEL SECURITY;

CREATE POLICY profiles_owner ON profiles FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

CREATE POLICY jobs_owner ON jobs FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

CREATE POLICY job_events_owner ON job_events FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());

CREATE POLICY agent_tasks_owner ON agent_tasks FOR ALL
  USING (owner_id = auth.uid()) WITH CHECK (owner_id = auth.uid());


